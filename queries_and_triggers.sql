/* ==========================================================================
   1. АНАЛІТИЧНІ ТА ФІЛЬТРАЦІЙНІ ЗАПИТИ (DATA SELECTION & ANALYSIS)
   ========================================================================== */

-- Фільтрація: вибір ігор дорожче 500 грн з рейтингом 18+
SELECT Назва_гри, Ціна, Віковий_рейтинг
FROM ГРА
WHERE Ціна > 500 AND Віковий_рейтинг = '18+';

-- Пошук за шаблоном (LIKE) та у діапазоні дат (BETWEEN)
SELECT Назва_гри 
FROM ГРА 
WHERE Назва_гри LIKE '[a]%';

SELECT Назва_гри, Дата_виходу 
FROM ГРА 
WHERE Дата_виходу BETWEEN '2015-01-01' AND '2020-12-31';

-- Об’єднання таблиць (JOIN): отримання інформації про ігри та їхніх розробників
SELECT ГРА.Назва_гри, РОЗРОБНИК.Назва_студії
FROM ГРА
JOIN РОЗРОБНИК ON ГРА.Код_розробника = РОЗРОБНИК.Код_розробника;

-- Агрегація та групування (GROUP BY): підрахунок кількості ігор у кожного розробника
SELECT РОЗРОБНИК.Назва_студії, COUNT(ГРА.Код_гри) AS Кількість_ігор
FROM РОЗРОБНИК
LEFT JOIN ГРА ON РОЗРОБНИК.Код_розробника = ГРА.Код_розробника
GROUP BY РОЗРОБНИК.Назва_студії;

-- Запити з обчисленнями: розрахунок ціни з урахуванням 20% ПДВ
SELECT Назва_гри, Ціна AS Базова_ціна, Ціна * 1.2 AS 'Ціна з ПДВ'
FROM ГРА;

-- Складна логіка (CASE): сегментація ігор за ціновими категоріями
SELECT Назва_гри, Ціна,
       Категорія = CASE 
           WHEN Ціна = 0 THEN N'Безкоштовно'
           WHEN Ціна <= 500 THEN N'Бюджетна'
           ELSE N'Преміум'
       END
FROM ГРА;

-- Аналітика відгуків: вибір ігор з ідеальними оцінками (10/10), сортування за новизною
SELECT ГРА.Назва_гри, ВІДГУК.Оцінка, ВІДГУК.Текст_відгуку, ВІДГУК.Дата_написання
FROM ГРА
JOIN ВІДГУК ON ГРА.Код_гри = ВІДГУК.Код_гри
WHERE ВІДГУК.Оцінка = 10
ORDER BY ВІДГУК.Дата_написання DESC;

-- Фільтрація груп (HAVING): пошук ігор, які не мають жодної оцінки вище 8
SELECT ГРА.Назва_гри, MAX(ВІДГУК.Оцінка) AS Найбільша_оцінка
FROM ГРА
JOIN ВІДГУК ON ГРА.Код_гри = ВІДГУК.Код_гри
GROUP BY ГРА.Назва_гри
HAVING MAX(ВІДГУК.Оцінка) <= 8;

-- Статистика активності користувачів (кількість написаних відгуків)
SELECT КОРИСТУВАЧ.Нікнейм, COUNT(ВІДГУК.Код_користувача) AS Кількість_відгуків
FROM КОРИСТУВАЧ
LEFT JOIN ВІДГУК ON КОРИСТУВАЧ.Код_користувача = ВІДГУК.Код_користувача
GROUP BY КОРИСТУВАЧ.Нікнейм;


