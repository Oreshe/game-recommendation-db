-- Тригер 1: Логування реєстрації нового користувача
GO
CREATE TRIGGER триг_ПісляДодавКорист
ON КОРИСТУВАЧ
AFTER INSERT
AS
BEGIN
    PRINT N'Система: Нового користувача успішно зареєстровано!';
END;
GO

-- Тригер 2: Валідація даних (заборона оцінок поза діапазоном 1-10)
GO
CREATE TRIGGER триг_ОбмеженняОцінювання
ON ВІДГУК
AFTER INSERT
AS
BEGIN
    IF EXISTS (SELECT 1 FROM inserted WHERE Оцінка > 10 OR Оцінка < 1)
    BEGIN
        PRINT N'Помилка: Оцінка має бути в межах від 1 до 10!';
        ROLLBACK TRANSACTION;
    END
END;
GO

-- Тригер 3: КРИТИЧНИЙ. Автоматичний перерахунок середнього рейтингу гри в реальному часі
GO
CREATE TRIGGER триг_ОновлОцінки
ON ВІДГУК
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE ГРА
    SET Середня_оцінка = (
        SELECT AVG(CAST(Оцінка AS FLOAT)) 
        FROM ВІДГУК 
        WHERE ВІДГУК.Код_гри = ГРА.Код_гри
    )
    WHERE Код_гри IN (
        SELECT Код_гри FROM inserted
        UNION
        SELECT Код_гри FROM deleted
    );

    PRINT N'Система: Рейтинг гри автоматично перераховано в реальному часі.';
END;
GO

-- Тригер 4: Захист даних (заборона редагування дати виходу для ігор релізу до 2014 року)
GO
CREATE TRIGGER триг_ЗаборонаОновлСтарихІгор
ON ГРА
AFTER UPDATE
AS
BEGIN
    IF EXISTS (SELECT 1 FROM deleted WHERE Дата_виходу < '2014-01-01') AND UPDATE(Дата_виходу)
    BEGIN
        PRINT N'Відмова: Заборонено змінювати дату виходу для старих ігор!';
        ROLLBACK TRANSACTION;
    END
END;
GO

-- Тригер 5: Каскадна перевірка цілісності при видаленні (INSTEAD OF DELETE)
GO
CREATE TRIGGER триг_ЗаборонаВидаленняРозробн
ON РОЗРОБНИК
INSTEAD OF DELETE 
AS
BEGIN
    IF EXISTS (SELECT 1 FROM deleted JOIN ГРА ON deleted.Код_розробника = ГРА.Код_розробника)
    BEGIN
        PRINT N'Помилка: Неможливо видалити розробника, поки в базі є його ігри!';
    END
    ELSE
    BEGIN
        DELETE FROM РОЗРОБНИК WHERE Код_розробника IN (SELECT Код_розробника FROM deleted);
    END
END;
GO

-- Тригер 6: Валідація фінансових даних (ціна не може бути від'ємною)
GO
CREATE TRIGGER триг_ПеревіркаЦіниНаДодатк
ON ГРА
AFTER INSERT, UPDATE
AS
BEGIN
    IF EXISTS (SELECT 1 FROM inserted WHERE Ціна < 0)
    BEGIN
        PRINT N'Помилка: Ціна гри не може бути від’ємною!';
        ROLLBACK TRANSACTION;
    END
END;
